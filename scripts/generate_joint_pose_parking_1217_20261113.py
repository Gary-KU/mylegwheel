"""Generate the1.6kg joint pose/parking DLQR candidate, with offline screens.

Default is report-only. --write updates only the six named model/evaluator
artifacts after all declared numeric screens pass. No SWD, actuator commands,
production task/config edits, header physics edits or firmware deployment.
The report is a model screen, not proof that this grounded robot will stand.
"""
from pathlib import Path
import argparse
import copy
import hashlib
import json
import math
import re
import sys
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'diagnostics'))
import analyze_pose_parking_joint_1216_20261113 as screen
sys.path.insert(0,str(ROOT/'tests'))
from verify_lqr_extended_domain import discrete_plant, independent_dlqr

REPORT=ROOT/'diagnostics/joint_pose_parking_1217_1600g_fit_20261113.json'
ARTIFACTS=('Control/WheelLeg/Src/lqr_k.c','Control/WheelLeg/Inc/lqr_k.h',
 'models/lqr/lqr_coefficients.csv','models/lqr/lqr_model_metadata.json',
 'models/lqr/lqr_k.m','models/lqr/lqr_model_parameters.m')


def design_parameters():
    p=copy.deepcopy(screen.P)
    p['total_mass_kg']=1.6;p['body_mass_kg']=1.25
    p['body_pitch_inertia_per_side']=p['body_mass_kg']*(p['body_length_m']**2+p['body_height_m']**2)/24
    p['support_feedforward_n']=(p['body_mass_kg']/2+p['leg_mass_per_side_kg'])*p['gravity_m_s2']
    p['Q']=[800,15,200,40,200,80];p['R']=[100000,10000];p['feedback_gain_scale']=[1,1]
    return p


def equilibrium(p,L,phi):
    m=p['body_mass_kg']/2;ml=p['leg_mass_per_side_kg'];h=p['body_com_height_m']
    theta=m*h/(m*L+ml*L/2)*phi
    tp=-m*p['gravity_m_s2']*h*phi
    return theta,tp


def write_artifacts(p,co,metadata):
    src=ROOT/ARTIFACTS[0]
    old=src.read_text(encoding='utf-8')
    match=re.search(r'^void\s+lqr_k\s*\([^)]*\)\s*\{.*?^\}',old,re.M|re.S)
    assert match
    suffix=old[match.end():]
    lines=['/* Generated by scripts/generate_joint_pose_parking_1217_20261113.py.',
      ' * Joint DLQR: Q=[800,15,200,40,200,80], R=[100000,10000], Ts=5ms.',
      ' * Total1.600kg; body1.250kg (.625kg per side); COM height40mm estimated.',
      ' * Cubic fit4..15cm; runtime4..15cm. Two joint feedback rows; no row scaling.',
      ' * Filter/input-gain/slew model screens are not physical stability proof.',
      ' * MATLAB column-major2x6; public control interface and conventions unchanged. */',
      '#include "lqr_k.h"','#include <math.h>','void lqr_k(float L0, float K[12])','{']
    for n,row in enumerate(co):
        c3,c2,c1,c0=[f'{v:.17e}f' for v in row]
        lines.append(f'    K[{n}] = (({c3}*L0 + ({c2}))*L0 + ({c1}))*L0 + ({c0});')
    new='\n'.join(lines+['}'])+suffix
    assert new[new.index('static inline'):]==old[old.index('static inline'):]
    src.write_text(new,encoding='utf-8')
    header=ROOT/ARTIFACTS[1]
    text=header.read_text(encoding='utf-8')
    start=text.index('/* Model:');end=text.index(' */',start)+3
    text=text[:start]+'''/* Model:1.600kg total,1.250kg body (.625kg per side).
 * Wheel/leg split and body COM height40mm are estimates; see metadata.
 * K[row+2*column]; state=[theta,dtheta,x,dx,phi,dphi].
 * Units: rad,rad/s,m,m/s,rad,rad/s; output=[T,Tp] in N*m.
 * Joint DLQR Q=[800,15,200,40,200,80],R=[100000,10000]; no row scaling.
 * Cubic samples4..15cm; runtime4..15cm. Regenerated2026-11-13.
 * Reproduce: scripts/generate_joint_pose_parking_1217_20261113.py.
 * Eight-state filtered/gain and constrained-slew screens are model checks.
 * Caller enforces runtime domain; real standing/parking needs a new trial.
 */'''+text[end:]
    header.write_text(text,encoding='utf-8')
    np.savetxt(ROOT/ARTIFACTS[2],co,delimiter=',',fmt='%.17e')
    (ROOT/ARTIFACTS[3]).write_text(json.dumps(metadata,indent=2)+'\n',encoding='utf-8')
    ml=['function K = lqr_k(L0)',
       '% Generated by scripts/generate_joint_pose_parking_1217_20261113.py.',
       '% Joint DLQR1.600kg,Q=[800 15 200 40 200 80],R=[100000 10000].',
       '% Fit4..15cm; runtime4..15cm. This is not physical validation.',
       't2=L0.^2;','t3=L0.^3;']
    for n,(a,b,c,d) in enumerate(co,1):ml.append(f'mt{n}=[({a:.17e}).*t3+({b:.17e}).*t2+({c:.17e}).*L0+({d:.17e})];')
    ml.append('K=reshape(['+','.join(f'mt{n}' for n in range(1,13))+'],2,6);')
    ml+=['end',''];(ROOT/ARTIFACTS[4]).write_text('\n'.join(ml),encoding='utf-8')
    params=ROOT/ARTIFACTS[5]
    txt=params.read_text(encoding='utf-8')
    txt=re.sub(r'p.total_mass_kg=[^;]+;','p.total_mass_kg=1.600;',txt)
    txt=re.sub(r'p.Q=\[[^]]+\];[^\n]*','p.Q=[800 15 200 40 200 80]; % Joint pose/parking candidate,2026-11-13.',txt)
    txt=re.sub(r'p.R=\[[^]]+\];[^\n]*','p.R=[100000 10000]; % Joint DARE input cost; no row multipliers.',txt)
    txt=txt.replace('% Confirmed whole-robot and non-body mass. Wheel/leg split is estimated.',
      '% Whole-robot mass1.6kg; non-body350g and wheel/leg split remain estimates.\n% Canonical cubic-fit generator: scripts/generate_joint_pose_parking_1217_20261113.py.')
    params.write_text(txt,encoding='utf-8')


def main():
    args=argparse.ArgumentParser(description=__doc__)
    args.add_argument('--write',action='store_true');args=args.parse_args()
    p=design_parameters();co=np.zeros((12,4));sample_lengths=np.linspace(.04,.15,12)
    values=[]
    for L in sample_lengths:
        a,b=discrete_plant(p,float(L));k=screen.dare_fast(a,b,np.diag(p['Q']),np.diag(p['R']))
        values.append(k.reshape(12,order='F'))
    values=np.array(values)
    for j in range(12):co[j]=np.polyfit(sample_lengths,values[:,j],3)
    def fitted(L):
        v=np.float32(L);c=co.astype(np.float32)
        return (((c[:,0]*v+c[:,1])*v+c[:,2])*v+c[:,3]).astype(float).reshape((2,6),order='F')
    # Cross-check an independent iterative Riccati solution after mass change.
    a,b=discrete_plant(p,.09);ki,_=independent_dlqr(a,b,p)
    kf=screen.dare_fast(a,b,np.diag(p['Q']),np.diag(p['R']))
    assert max(abs((ki-kf).flatten()))<1e-8
    fits=[];radii=[];double_radii=[]
    for L in np.linspace(.04,.15,111):
        a,b=discrete_plant(p,float(L));ke=screen.dare_fast(a,b,np.diag(p['Q']),np.diag(p['R']))
        k=fitted(float(L));rho=float(max(abs(np.linalg.eigvals(a-b@k))))
        double_k=(co@[L**3,L**2,L,1]).reshape((2,6),order='F')
        double_radii.append(float(max(abs(np.linalg.eigvals(a-b@double_k)))))
        radii.append(rho)
        fits.append(dict(length_m=float(L),relative_gain_fit_error=float(np.linalg.norm(k-ke)/np.linalg.norm(ke)),pole_radius=rho))
    original_gain=screen.gain
    c=dict(name='1217_1600g_joint_fit',Q=p['Q'],R=p['R'])
    screen.gain=lambda candidate,L:fitted(L)
    grid=[]
    for L in np.linspace(.07,.12,51):
        for mass in (1.47,1.6):
            for gw in (.7,1,1.3):
                for gh in (.7,1,1.3):
                    a,b=screen.plant(float(L),mass,(gw,gh));grid.append((float(L),mass,gw,gh,a,b))
    linear=screen.pole_screen(c,grid)
    replay=[screen.replay(c,w) for w in (.05,.3,.5)]
    snapshots=[min(screen.ROWS,key=lambda r:abs(r['elapsed_ms']-ms)) for ms in (1000,2000,4000)]
    rollouts=[screen.rollout(c,.3,row,mass,gains) for row in snapshots for mass in (1.47,1.6)
       for gains in ((1,1),(.7,1.3),(1.3,.7))]
    screen.gain=original_gain
    equilibrium_cases=[]
    for L in (.07,.09,.12):
        theta,tp=equilibrium(p,L,-math.radians(.5))
        ac,bc=screen.continuous_plant(p,L)
        residual=max(abs(ac@np.array([theta,0,0,0,-math.radians(.5),0])+bc@[0,tp]))
        equilibrium_cases.append(dict(length_m=L,phi_eq_deg=-.5,theta_eq_deg=math.degrees(theta),Tp_feedforward_nm=tp,residual=float(residual)))
    report=dict(scope=__doc__,parameters=p,fit_samples_m=sample_lengths.tolist(),
       coefficients=co.tolist(),six_state_fit_check=fits,eight_state_stress=linear,
       static_replay=replay,optimistic_slew_rollouts=rollouts,
       equilibrium_cases=equilibrium_cases,checks=dict(
           joint_dare_crosscheck_max_abs_error=float(max(abs((ki-kf).flatten()))),
           six_state_worst_radius=max(double_radii),six_state_float32_worst_radius=max(radii),eight_state_worst_radius=linear['worst_radius'],
           replay_window_point3_peak_joint_a=replay[1]['peak_joint_requested_iq_a'],
           replay_window_point3_peak_wheel_a=replay[1]['peak_wheel_requested_iq_a'],
           slew_rollout_completed=sum(r['result']=='completed8s' for r in rollouts),slew_rollout_total=len(rollouts)),
       assumptions=screen.__doc__,limitations=[
          'Independent wheel/hip gains0.7/1/1.3 are a stress grid, not a measured confidence interval.',
          'Window0.3m never changes the true goal; outside the window position slope is zero.',
          'Frozen geometry/symmetric8state slew rollouts omit vertical/differential/contact/friction/current loop/voltage/delays.',
          'Slew rollouts retain1216 inconsistent trim references to expose risk; candidate integration must use physical equilibrium reference/feedforward.',
          'Passing these screens does not establish physical recovery; baseline passed despite grounded1216 runaway.',
          'No positive-direction breakaway threshold identified. This mild joint candidate does not claim to overcome measured friction.'
       ],write_requested=args.write,written=False)
    passing=(max(radii)<1 and linear['worst_radius']<1 and replay[1]['peak_joint_requested_iq_a']<2
      and replay[1]['peak_wheel_requested_iq_a']<2 and all(r['result']=='completed8s' for r in rollouts))
    report['numeric_screen_pass']=passing
    metadata=dict(parameters=p,mass_split_estimated=True,max_linear_pole_radius=max(double_radii),
       state_order=['theta','dtheta','x','dx','phi','dphi'],matrix_storage='MATLAB column-major2x6: K[row+2*column]',
       firmware_feedback='u=-K*(state-reference)',simscape_feedback='u=+K*x because actuator coordinates oppose analytical inputs',
       generator='scripts/generate_joint_pose_parking_1217_20261113.py',
       fit_sample_lengths_m=sample_lengths.tolist(),cubic_fit_degree=3,
       eight_state_screen=dict(worst_radius=linear['worst_radius'],length_m=[.07,.12],mass_kg=[1.47,1.6],independent_input_gains=[.7,1,1.3]),
       validation_report=str(REPORT.relative_to(ROOT)),physical_validation='Pending new grounded hardware trial; numeric screens do not establish success.')
    if args.write:
        if not passing:
            REPORT.write_text(json.dumps(report,indent=2,default=lambda v:v.item() if isinstance(v,np.generic) else str(v)),encoding='utf-8')
            raise SystemExit('Candidate failed declared numeric screens; no model artifacts changed')
        write_artifacts(p,co,metadata);report['written']=True
        report['artifact_sha256']={f:hashlib.sha256((ROOT/f).read_bytes()).hexdigest() for f in ARTIFACTS}
    REPORT.write_text(json.dumps(report,indent=2,default=lambda v:v.item() if isinstance(v,np.generic) else str(v)),encoding='utf-8')
    print(json.dumps(dict(report=str(REPORT),numeric_screen_pass=passing,written=report['written'],checks=report['checks'],
       worst_case=linear['worst_case_length_mass_wheelgain_hipgain'],equilibrium_cases=equilibrium_cases),indent=2))


if __name__=='__main__':main()
