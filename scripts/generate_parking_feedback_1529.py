"""Generate the1529 coupled parking LQI candidate; no target access.

The1528 ring shows small common hip-angle motion despite changing common Tp.
Increasing hip effort cost is a robust-control hypothesis that reallocates the
complete two-output controller; it is not an identified actuator model.
Default output is private diagnostics. Production installation is explicit.
"""
from pathlib import Path
import argparse
import hashlib
import json
import sys
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tests'))
from verify_foc_sampled_timing import continuous_plant
from verify_lqr_extended_domain import exponential
from generate_parking_servo_1424 import dare

DESIGN_DRAG=.00025
Q=[800,15,200,40,8000,80,100]
R=[100000,40000]

def gain(parameters,length):
    a,b=continuous_plant(parameters,length)
    port=np.array([0,-1,0,1/parameters['wheel_radius_m'],0,0])
    a-=DESIGN_DRAG*np.outer(b[:,0],port)
    aug=np.zeros((8,8));aug[:6,:6]=a;aug[:6,6:]=b
    d=exponential(aug*parameters['Ts'])
    # Output uses physical z_k; after output, z_(k+1)=z_k+Ts*x_error.
    aa=np.eye(7);aa[:6,:6]=d[:6,:6];aa[6,2]=parameters['Ts']
    bb=np.zeros((7,2));bb[:6]=d[:6,6:]
    return dare(aa,bb,np.diag(Q),np.diag(R))

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=ROOT/'diagnostics/balance_parking_feedback_1529_private.h')
    parser.add_argument('--report',type=Path,default=ROOT/'diagnostics/parking1529_gain_generation.json')
    args=parser.parse_args()
    p=json.loads((ROOT/'models/lqr/lqr_model_metadata.json').read_text())['parameters'];assert p['Ts']==.005
    knots=np.linspace(.04,.15,45)
    table=np.array([np.r_[k[:,:6].reshape(-1,order='F'),k[:,6]] for k in (gain(p,float(L)) for L in knots)],np.float32)
    max_abs=max_relative=0
    for L in np.linspace(.04,.15,221):
        at=min(43,int(np.floor((L-.04)/.0025+1e-10)));t=(L-knots[at])/.0025
        exact=gain(p,float(L));expected=np.r_[exact[:,:6].reshape(-1,order='F'),exact[:,6]]
        error=abs(table[at]*(1-t)+table[at+1]*t-expected)
        max_abs=max(max_abs,float(max(error)));max_relative=max(max_relative,float(max(error/np.maximum(.001,abs(expected)))))
    assert np.isfinite(table).all() and max_abs<.001
    def literal(value):
        text=f'{float(value):.9g}';return (text if '.' in text or 'e' in text else text+'.0')+'f'
    rows='\n'.join('    {'+', '.join(map(literal,row))+'},' for row in table)
    header='''/* Generated by scripts/generate_parking_feedback_1529.py.
 * Parking coupled LQI: Q=[800,15,200,40,8000,80,100], R=[100000,40000].
 * Design wheel-port drag=.00025Nm*s/rad; Ts=.005s; same physical z timing.
 * Hip effort cost is raised jointly in DARE; no isolated state/row scaling.
 * Driving/startup gains, DC references, fixed goal and current caps retained.
 * Model/effort hypotheses require hardware retest; no identified friction/Kt.
 */
#ifndef BALANCE_PARKING_GAINS_H
#define BALANCE_PARKING_GAINS_H
#include <math.h>
static const float balance_parking_gain_table[45][14]={
'''+rows+'''
};
static inline int BalanceParking_Gain(float length,float K[12],float Ki[2]) {
    if(!K || !Ki || !isfinite(length) || length<0.04f || length>0.15f)return 0;
    float grid=(length-0.04f)*400.0f;
    unsigned index=(unsigned)grid;
    if(index>43U)index=43U;
    float t=grid-(float)index;
    if(t<0)t=0;
    if(t>1)t=1;
    for(unsigned i=0;i<12;++i)K[i]=balance_parking_gain_table[index][i]+t*(balance_parking_gain_table[index+1][i]-balance_parking_gain_table[index][i]);
    for(unsigned i=0;i<2;++i)Ki[i]=balance_parking_gain_table[index][12+i]+t*(balance_parking_gain_table[index+1][12+i]-balance_parking_gain_table[index][12+i]);
    return 1;
}
#endif
'''
    args.output.parent.mkdir(parents=True,exist_ok=True);args.output.write_text(header,encoding='utf-8')
    sources=('scripts/generate_parking_feedback_1529.py','scripts/generate_parking_servo_1424.py',
        'tests/verify_foc_sampled_timing.py','tests/verify_lqr_extended_domain.py','models/lqr/lqr_model_metadata.json')
    report=dict(scope=__doc__,Q=Q,R=R,sample_s=p['Ts'],design_drag_nm_s_per_rad=DESIGN_DRAG,
        integral_timing='u_k=-K*error_k-Ki*z_k+ff_k; z_next=z_k+Ts*x_error_k',
        knots_m=knots.tolist(),interpolation_max_abs_gain_error=max_abs,
        interpolation_max_relative_gain_error=max_relative,relative_gain_floor=.001,
        output=str(args.output.resolve()),output_sha256=hashlib.sha256(args.output.read_bytes()).hexdigest(),
        source_sha256={n:hashlib.sha256((ROOT/n).read_bytes()).hexdigest() for n in sources},
        gain_table_column_major_K_then_Ki=table.astype(float).tolist(),
        limitation='Generation and interpolation only. Acceptance requires paired production-C/current-slew/geometry screens and a hardware retest.')
    args.report.parent.mkdir(parents=True,exist_ok=True);args.report.write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({k:v for k,v in report.items() if k not in ('knots_m','gain_table_column_major_K_then_Ki','source_sha256')},indent=2))
if __name__=='__main__':main()
