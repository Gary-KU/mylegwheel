"""Generate the selected neutral-parking coupled LQI; no target access.

The wheel-port viscous load is a conservative design proxy, not an identified
friction measurement. Driving retains the existing 1424 gains. Selection and
finite-current/slew comparison reports live under diagnostics/parking1525*.
"""
from pathlib import Path
import argparse
import hashlib
import json
import sys
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'tests'))
from verify_foc_sampled_timing import continuous_plant
from verify_lqr_extended_domain import exponential
from generate_parking_servo_1424 import dare

DESIGN_DRAG = .00025


def gain(parameters, length):
    a, b = continuous_plant(parameters, length)
    port = np.array([0, -1, 0, 1/parameters['wheel_radius_m'], 0, 0])
    a -= DESIGN_DRAG*np.outer(b[:, 0], port)
    aug = np.zeros((8, 8)); aug[:6, :6] = a; aug[:6, 6:] = b
    d = exponential(aug*parameters['Ts'])
    aa = np.eye(7); aa[:6, :6] = d[:6, :6]; aa[6, 2] = parameters['Ts']
    bb = np.zeros((7, 2)); bb[:6] = d[:6, 6:]
    q = np.diag([800, 15, 200, 40, 8000, 80, 100])
    return dare(aa, bb, q, np.diag(parameters['R']))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT/'Control/WheelLeg/Inc/balance_parking_gains.h')
    parser.add_argument('--report', type=Path, default=ROOT/'diagnostics/parking1525_gain_generation.json')
    args = parser.parse_args()
    p = json.loads((ROOT/'models/lqr/lqr_model_metadata.json').read_text())['parameters']
    assert p['Ts'] == .005
    knots = np.linspace(.04, .15, 45)
    tables = [gain(p, float(length)) for length in knots]
    table = np.array([np.r_[k[:, :6].reshape(-1, order='F'), k[:, 6]] for k in tables], np.float32)
    max_abs_error = 0
    for length in np.linspace(.04, .15, 221):
        at = min(43, int(np.floor((length-.04)/.0025+1e-10)))
        t = (length-knots[at])/.0025
        exact = gain(p, float(length))
        expected = np.r_[exact[:, :6].reshape(-1, order='F'), exact[:, 6]]
        max_abs_error = max(max_abs_error, float(max(abs(table[at]*(1-t)+table[at+1]*t-expected))))
    assert np.isfinite(table).all() and max_abs_error < .001
    def literal(value):
        text = f'{float(value):.9g}'
        return (text if '.' in text or 'e' in text else text+'.0')+'f'
    rows = '\n'.join('    {'+', '.join(map(literal, row))+'},' for row in table)
    header = '''/* Generated by scripts/generate_parking_damping_1525.py.
 * Neutral-only coupled LQI: Q=[800,15,200,40,8000,80,100], R=[100000,10000].
 * Design wheel-port drag=0.00025 Nm*s/rad; Ts=.005s. This is a model proxy,
 * not a measured friction value. Complete T/Tp and Ki rows are solved jointly.
 * Driving/startup gains, fixed goal and actuator current limits are retained.
 */
#ifndef BALANCE_PARKING_GAINS_H
#define BALANCE_PARKING_GAINS_H
#include <math.h>
static const float balance_parking_gain_table[45][14]={
'''+rows+'''
};
static inline int BalanceParking_Gain(float length,float K[12],float Ki[2]) {
    if(!K || !Ki || !isfinite(length) || length<0.04f || length>0.15f)return 0;
    float grid=(length-0.04f)*400.0f;
    unsigned index=(unsigned)grid;
    if(index>43U)index=43U;
    float t=grid-(float)index;
    if(t<0)t=0;
    if(t>1)t=1;
    for(unsigned i=0;i<12;++i)K[i]=balance_parking_gain_table[index][i]+t*(balance_parking_gain_table[index+1][i]-balance_parking_gain_table[index][i]);
    for(unsigned i=0;i<2;++i)Ki[i]=balance_parking_gain_table[index][12+i]+t*(balance_parking_gain_table[index+1][12+i]-balance_parking_gain_table[index][12+i]);
    return 1;
}
#endif
'''
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header, encoding='utf-8')
    sources = ('scripts/generate_parking_damping_1525.py', 'scripts/generate_parking_servo_1424.py',
               'tests/verify_foc_sampled_timing.py', 'tests/verify_lqr_extended_domain.py',
               'models/lqr/lqr_model_metadata.json')
    report = dict(scope=__doc__, design_drag_nm_s_per_rad=DESIGN_DRAG,
        Q=[800,15,200,40,8000,80,100], R=p['R'], sample_s=p['Ts'], knots_m=knots.tolist(),
        interpolation_max_abs_gain_error=max_abs_error,
        source_sha256={name:hashlib.sha256((ROOT/name).read_bytes()).hexdigest() for name in sources},
        output=str(args.output.resolve()), output_sha256=hashlib.sha256(args.output.read_bytes()).hexdigest(),
        gain_table_column_major_K_then_Ki=table.astype(float).tolist(),
        limitation='Numerical generation only; acceptance requires paired production-C plant-loop tests and hardware retest.')
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8')
    print(json.dumps({k:v for k,v in report.items() if k not in ('gain_table_column_major_K_then_Ki','knots_m','source_sha256')}, indent=2))


if __name__ == '__main__':
    main()
