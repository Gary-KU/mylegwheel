def design_parameters():
    p=copy.deepcopy(json.loads((ROOT/ARTIFACTS[3]).read_text(encoding='utf-8'))['parameters'])
    # Preserve the reviewed physical model. This trial changes two costs only.
    assert p['total_mass_kg']==1.6 and p['body_mass_kg']==1.25
    assert p['non_body_mass_kg']==.35 and p['body_com_height_m']==.04
    assert p['Ts']==.005 and p['length_min_m']==.04 and p['length_max_m']==.15
    assert p['feedback_gain_scale']==[1,1]
    p['Q']=list(Q);p['R']=list(R)
    return p


def doubled_dare(a,b,q,r):
    """Structure-preserving doubling, independently checked by Riccati iteration."""
    aa=a.copy();gg=b@np.linalg.solve(r,b.T);hh=q.copy();eye=np.eye(len(a))
    for iterations in range(1,81):
        w=np.linalg.solve(eye+gg@hh,aa)
        an=aa@w
        gn=gg+aa@gg@np.linalg.solve(eye+hh@gg,aa.T)
        hn=hh+aa.T@hh@w
        gn=(gn+gn.T)/2;hn=(hn+hn.T)/2
        if np.linalg.norm(hn-hh,np.inf)<1e-11*max(1,np.linalg.norm(hn,np.inf)):
            hh=hn;break
        aa,gg,hh=an,gn,hn
    else:raise RuntimeError('Doubling DARE did not converge')
    k=np.linalg.solve(r+b.T@hh@b,b.T@hh@a)
    residual=a.T@hh@a-a.T@hh@b@k+q-hh
    relative_residual=float(np.linalg.norm(residual,np.inf)/max(1,np.linalg.norm(hh,np.inf)))
    assert relative_residual<1e-9
    return k,relative_residual


def continuous_model(p,length):
    m=p['body_mass_kg']/2;ml=p['leg_mass_per_side_kg'];h=p['body_com_height_m'];r=p['wheel_radius_m']
    inertia=np.array([[m+ml+p['wheel_mass_per_side_kg']+p['wheel_inertia_per_side']/r**2,
        m*length+ml*length/2,-m*h],
        [m*length+ml*length/2,p['leg_inertia_per_side']+ml*(length/2)**2+m*length**2,-m*length*h],
        [-m*h,-m*length*h,p['body_pitch_inertia_per_side']+m*h*h]])
    a=np.zeros((6,6));b=np.zeros((6,2));a[0,1]=a[2,3]=a[4,5]=1
    a[[3,1,5],0]=np.linalg.solve(inertia,[0,(m+ml/2)*length*p['gravity_m_s2'],0])
    a[[3,1,5],4]=np.linalg.solve(inertia,[0,0,m*p['gravity_m_s2']*h])
    b[[3,1,5]]=np.linalg.solve(inertia,[[1/r,0],[-1,1],[0,1]])
    return a,b


def zoh(a,b,dt):
    n,m=b.shape;aug=np.zeros((n+m,n+m));aug[:n,:n]=a;aug[:n,n:]=b
    value=exponential(aug*dt)
    return value[:n,:n],value[:n,n:]


def filtered_radius(p,length,k,input_gains=(1,1)):
    a0,b0=continuous_model(p,length)
    a=np.zeros((8,8));b=np.zeros((8,2));a[:6,:6]=a0;b[:6]=b0@np.diag(input_gains)
    a[6,[1,5,6]]=[50,50,-50];a[7,[3,7]]=[50,-50]
    measurement=np.zeros((6,8))
    measurement[0,0]=measurement[2,2]=measurement[4,4]=measurement[5,5]=1
    measurement[1,6]=1;measurement[1,5]=-1
    measurement[2,7]=-.020;measurement[3,7]=1
    ad,bd=zoh(a,b,p['Ts'])
    return float(max(abs(np.linalg.eigvals(ad-bd@k@measurement))))


def write_artifacts(p,co,metadata):
    src=ROOT/ARTIFACTS[0];old=src.read_text(encoding='utf-8')
    match=re.search(r'^void\s+lqr_k\s*\([^)]*\)\s*\{.*?^\}',old,re.M|re.S)
    assert match
    suffix=old[match.end():]
    lines=[f'/* Generated by {GENERATOR}.',
        ' * Joint DLQR damping trial: Q=[800,15,200,80,200,160], R=[100000,10000], Ts=5ms.',
        ' * Total1.600kg; body1.250kg (.625kg per side); COM height40mm estimated.',
        ' * Cubic fit4..15cm; runtime4..15cm. Both coupled feedback rows retained.',
        ' * No row scaling; model screens are not proof of real stationary parking.',
        ' * MATLAB column-major2x6; public evaluator interfaces/conventions unchanged. */',
        '#include "lqr_k.h"','#include <math.h>','void lqr_k(float L0, float K[12])','{']
    for n,row in enumerate(co):
        a,b,c,d=[f'{v:.17e}f' for v in row]
        lines.append(f'    K[{n}] = (({a}*L0 + ({b}))*L0 + ({c}))*L0 + ({d});')
    new='\n'.join(lines+['}'])+suffix
    regenerated=re.search(r'^void\s+lqr_k\s*\([^)]*\)\s*\{.*?^\}',new,re.M|re.S)
    assert new[regenerated.end():]==suffix
    src.write_text(new,encoding='utf-8')
    header=ROOT/ARTIFACTS[1];text=header.read_text(encoding='utf-8')
    start=text.index('/* Model:');end=text.index(' */',start)+3
    text=text[:start]+f'''/* Model:1.600kg total,1.250kg body (.625kg per side).
 * Wheel/leg split and body COM height40mm are estimates; see metadata.
 * K[row+2*column]; state=[theta,dtheta,x,dx,phi,dphi].
 * Units: rad,rad/s,m,m/s,rad,rad/s; output=[T,Tp] in N*m.
 * Joint damping-trial DLQR Q=[800,15,200,80,200,160],R=[100000,10000].
 * Both feedback rows retained; no row multipliers or new actuator limits.
 * Cubic samples4..15cm; runtime4..15cm. Regenerated2026-11-14.
 * Reproduce: {GENERATOR}.
 * Independent DARE/fit and filtered-input-gain screens are model checks.
 * Real standing/parking and delay/contact robustness require new trials.
 */'''+text[end:]
    header.write_text(text,encoding='utf-8')
    np.savetxt(ROOT/ARTIFACTS[2],co,delimiter=',',fmt='%.17e')
    (ROOT/ARTIFACTS[3]).write_text(json.dumps(metadata,indent=2)+'\n',encoding='utf-8')
    ml=['function K = lqr_k(L0)',f'% Generated by {GENERATOR}.',
        '% Joint damping-trial DLQR1.600kg,Q=[800 15 200 80 200 160],R=[100000 10000].',
        '% Fit4..15cm; runtime4..15cm. Model screens are not hardware validation.',
        't2=L0.^2;','t3=L0.^3;']
    for n,(a,b,c,d) in enumerate(co,1):ml.append(f'mt{n}=[({a:.17e}).*t3+({b:.17e}).*t2+({c:.17e}).*L0+({d:.17e})];')
    ml+=['K=reshape(['+','.join(f'mt{n}' for n in range(1,13))+'],2,6);','end','']
    (ROOT/ARTIFACTS[4]).write_text('\n'.join(ml),encoding='utf-8')
    params=ROOT/ARTIFACTS[5];txt=params.read_text(encoding='utf-8')
    txt=re.sub(r'^% Canonical cubic-fit generator:.*$',f'% Canonical cubic-fit generator: {GENERATOR}.',txt,flags=re.M)
    txt=re.sub(r'p.Q=\[[^]]+\];[^\n]*','p.Q=[800 15 200 80 200 160]; % Joint damping trial,2026-11-14.',txt)
    txt=re.sub(r'p.R=\[[^]]+\];[^\n]*','p.R=[100000 10000]; % Joint DARE input cost; no row multipliers.',txt)
    params.write_text(txt,encoding='utf-8')


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--write',action='store_true')
    args=parser.parse_args();p=design_parameters();samples=np.linspace(.04,.15,12)
    values=[];residuals=[]
    for length in samples:
        a,b=discrete_plant(p,float(length));k,residual=doubled_dare(a,b,np.diag(Q),np.diag(R))
        values.append(k.reshape(12,order='F'));residuals.append(residual)
    values=np.array(values);co=np.array([np.polyfit(samples,values[:,i],3) for i in range(12)])
    def fitted(length,single=False):
        if single:
            v=np.float32(length);c=co.astype(np.float32)
            raw=((c[:,0]*v+c[:,1])*v+c[:,2])*v+c[:,3]
        else:raw=co@[length**3,length**2,length,1]
        return raw.astype(float).reshape((2,6),order='F')
    independent=[]
    for length in (.04,.071,.09,.15):
        a,b=discrete_plant(p,length);ki,iterations=independent_dlqr(a,b,p)
        ks,_=doubled_dare(a,b,np.diag(Q),np.diag(R))
        ac,bc=continuous_model(p,length);ad,bd=zoh(ac,bc,p['Ts'])
        assert max(np.max(abs(a-ad)),np.max(abs(b-bd)))<1e-12
        error=float(np.max(abs(ki-ks)));assert error<1e-7
        independent.append(dict(length_m=length,max_abs_gain_error=error,riccati_iterations=iterations))
    fits=[]
    for length in np.linspace(.04,.15,111):
        a,b=discrete_plant(p,float(length));exact,_=doubled_dare(a,b,np.diag(Q),np.diag(R))
        kd=fitted(float(length));kf=fitted(float(length),True)
        fits.append(dict(length_m=float(length),relative_f32_fit_error=float(np.linalg.norm(kf-exact)/np.linalg.norm(exact)),
            double_radius=float(max(abs(np.linalg.eigvals(a-b@kd)))),
            float32_radius=float(max(abs(np.linalg.eigvals(a-b@kf))))))
    stress=[]
    for length in np.linspace(.07,.12,51):
        for total_mass in (1.47,1.6):
            pp=copy.deepcopy(p);body=total_mass-pp['non_body_mass_kg']
            pp['body_pitch_inertia_per_side']*=body/pp['body_mass_kg'];pp['body_mass_kg']=body
            for gw in (.7,1,1.3):
                for gh in (.7,1,1.3):
                    stress.append(dict(length_m=float(length),total_mass_kg=total_mass,wheel_gain=gw,hip_gain=gh,
                        radius=filtered_radius(pp,float(length),fitted(float(length),True),(gw,gh))))
    worst=max(stress,key=lambda v:v['radius'])
    checks=dict(max_dare_relative_residual=max(residuals),max_independent_gain_error=max(v['max_abs_gain_error'] for v in independent),
        max_float32_gain_fit_error=max(v['relative_f32_fit_error'] for v in fits),
        six_state_worst_radius=max(v['double_radius'] for v in fits),
        six_state_float32_worst_radius=max(v['float32_radius'] for v in fits),
        eight_state_filtered_stress_worst_radius=worst['radius'])
    passed=(checks['max_float32_gain_fit_error']<.005 and checks['six_state_worst_radius']<1
        and checks['six_state_float32_worst_radius']<1 and checks['eight_state_filtered_stress_worst_radius']<1)
    metadata=dict(parameters=p,mass_split_estimated=True,max_linear_pole_radius=checks['six_state_worst_radius'],
        state_order=['theta','dtheta','x','dx','phi','dphi'],matrix_storage='MATLAB column-major2x6: K[row+2*column]',
        firmware_feedback='u=-K*(state-reference)',simscape_feedback='u=+K*x because actuator coordinates oppose analytical inputs',
        generator=GENERATOR,fit_sample_lengths_m=samples.tolist(),cubic_fit_degree=3,
        eight_state_screen=dict(worst_radius=worst['radius'],length_m=[.07,.12],mass_kg=[1.47,1.6],independent_input_gains=[.7,1,1.3]),
        validation_report=str(REPORT.relative_to(ROOT)),
        change_from_1219='Only joint design costs Q_speed40->80 and Q_bodyrate80->160; R/physical model/limits unchanged.',
        physical_validation='Damping trial only; stationary parking and nonlinear contact/friction/delay robustness not demonstrated.')
    report=dict(scope=__doc__,parameters=p,fit_samples_m=samples.tolist(),coefficients=co.tolist(),
        independent_iterative_DARE=independent,six_state_fit_and_poles=fits,
        eight_state_stress=dict(cases=len(stress),worst_case=worst,scope='20ms velocity LPF,5ms ZOH,7..12cm,1.47/1.6kg,gains0.7/1/1.3; no pure delay/contact/friction.'),
        checks=checks,numeric_screen_pass=passed,write_requested=args.write,written=False,
        input_model_sha256=hashlib.sha256((ROOT/ARTIFACTS[3]).read_bytes()).hexdigest(),
        limitations=['The broader h20..60mm/wheelgain0.5..1.5/5..10ms extra-delay grid has failing cases in baseline and candidate; see diagnostics/parking_model_1220_20261114.json.',
            'Full gen16 old-trajectory replay remains below2A, but does not simulate changed motion or a changed collision; see diagnostics/parking_trial2_replay_1220_20261114.json.',
            'No positive-direction breakaway threshold or nonlinear contact/friction model is identified.',
            'A numeric pass is not proof of stationary physical parking; actuator limits and controller protections are outside this polynomial.'],
        hardware_access=False)
    if args.write:
        if not passed:
            REPORT.write_text(json.dumps(report,indent=2),encoding='utf-8')
            raise SystemExit('Candidate failed declared numeric screens; no production model artifacts changed')
        write_artifacts(p,co,metadata);report['written']=True
        report['artifact_sha256']={name:hashlib.sha256((ROOT/name).read_bytes()).hexdigest() for name in ARTIFACTS}
    REPORT.write_text(json.dumps(report,indent=2,allow_nan=False),encoding='utf-8')
    print(json.dumps(dict(report=str(REPORT),numeric_screen_pass=passed,written=report['written'],checks=checks,
        worst_filtered_case=worst),indent=2))


if __name__=='__main__':main()
